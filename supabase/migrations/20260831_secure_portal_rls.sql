-- Portal Integrado N2 — sessão temporária e RLS por matrícula/perfil.
-- Corrige instalações que receberam as políticas amplas da migração anterior.

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.portal_sessoes (
  id bigint generated by default as identity primary key,
  token_hash text not null unique,
  matricula text not null,
  cpf text not null,
  nome text not null,
  cargo text not null,
  uorg_id text not null,
  nivel_acesso text not null default 'OURO',
  criado_em timestamptz not null default now(),
  expira_em timestamptz not null,
  ultimo_uso_em timestamptz not null default now()
);

create index if not exists portal_sessoes_expira_idx
  on public.portal_sessoes (expira_em);

alter table public.auditoria_eventos
  add column if not exists destinatario_matricula text;

create or replace function public.portal_token_requisicao()
returns text
language plpgsql
stable
set search_path = public, pg_temp
as $$
declare
  cabecalhos text;
begin
  cabecalhos := current_setting('request.headers', true);
  if cabecalhos is null or cabecalhos = '' then
    return null;
  end if;
  return nullif(cabecalhos::jsonb ->> 'x-portal-session', '');
exception when others then
  return null;
end;
$$;

create or replace function public.portal_sessao_atual()
returns table (
  matricula text,
  cpf text,
  nome text,
  cargo text,
  uorg_id text,
  nivel_acesso text
)
language sql
stable
security definer
set search_path = public, extensions, pg_temp
as $$
  select
    s.matricula,
    s.cpf,
    s.nome,
    s.cargo,
    s.uorg_id,
    s.nivel_acesso
  from public.portal_sessoes s
  where s.token_hash = encode(
    extensions.digest(public.portal_token_requisicao(), 'sha256'),
    'hex'
  )
    and s.expira_em > now()
  limit 1;
$$;

create or replace function public.portal_matricula_atual()
returns text
