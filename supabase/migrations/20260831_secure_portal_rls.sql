create or replace function public.portal_aplicar_identidade()
returns trigger
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  matricula_sessao text := public.portal_matricula_atual();
  nome_sessao text := public.portal_nome_atual();
  gestor boolean := public.portal_eh_gestor();
begin
  if matricula_sessao is null then
    raise exception 'Sessão do Portal inválida ou expirada'
      using errcode = '42501';
  end if;

  if tg_table_name = 'oficios' then
    if not gestor then
      raise exception 'Operação exclusiva do perfil DIAMANTE'
        using errcode = '42501';
    end if;

    if tg_op = 'INSERT' then
      new.criado_por_matricula := matricula_sessao;
    else
      new.criado_por_matricula := old.criado_por_matricula;
    end if;
  else
    if tg_op = 'INSERT' then
      new.matricula := matricula_sessao;
      new.nome_servidor := nome_sessao;
    else
      if not gestor then
        raise exception 'Atualização exclusiva do perfil DIAMANTE'
          using errcode = '42501';
      end if;
      new.matricula := old.matricula;
      new.nome_servidor := old.nome_servidor;
    end if;
  end if;

  new.atualizado_por_matricula := matricula_sessao;
  new.atualizado_por_nome := nome_sessao;
  return new;
end;
$$;

create or replace function public.portal_auditar_fluxo()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  novo jsonb := to_jsonb(new);
  antigo jsonb := case when tg_op = 'UPDATE' then to_jsonb(old) else '{}'::jsonb end;
  acao_evento text;
  matricula_ator text;
  nome_ator text;
  matricula_destino text;
  status_anterior text;
  status_novo text;
begin
  matricula_ator := coalesce(
    novo ->> 'atualizado_por_matricula',
    novo ->> 'criado_por_matricula',
    novo ->> 'matricula'
  );
  nome_ator := coalesce(
    novo ->> 'atualizado_por_nome',
    novo ->> 'nome_servidor',
    novo ->> 'responsavel'
  );
  matricula_destino := coalesce(novo ->> 'matricula', novo ->> 'criado_por_matricula');
  status_anterior := antigo ->> 'status';
  status_novo := novo ->> 'status';

  if tg_op = 'INSERT' then
    acao_evento := 'CRIACAO';
  elsif status_anterior is distinct from status_novo then
    acao_evento := 'ALTERACAO_STATUS';
  else
    acao_evento := 'ATUALIZACAO';
  end if;

  insert into public.auditoria_eventos (
    tabela, registro_id, protocolo, acao, status_anterior, status_novo,
    usuario_matricula, usuario_nome, destinatario_matricula, detalhes
  ) values (
    tg_table_name,
    coalesce(novo ->> 'id', 'sem-id'),
    novo ->> 'protocolo',
    acao_evento,
    status_anterior,
    status_novo,
    matricula_ator,
    nome_ator,
    matricula_destino,
    jsonb_build_object('prioridade', novo ->> 'prioridade')
  );

  if tg_op = 'UPDATE'
     and status_anterior is distinct from status_novo
     and matricula_destino is not null then
    insert into public.notificacoes (matricula, titulo, mensagem, modulo, protocolo)
    values (
      matricula_destino,
      'Atualização de solicitação',
      'O status foi alterado de ' || coalesce(status_anterior, 'não informado')
        || ' para ' || coalesce(status_novo, 'não informado') || '.',
      tg_table_name,
      novo ->> 'protocolo'
    );
  end if;

  return new;
end;
$$;

