create or replace function public.portal_preparar_fluxo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  prefixo text;
begin
  prefixo := case tg_table_name
    when 'oficios' then 'GAB'
    when 'solicitacoes_almoxarifado' then 'ALM'
    when 'solicitacoes_frota' then 'FRO'
    when 'chamados_patrimonio' then 'PAT'
    when 'solicitacoes_ferias' then 'FER'
    else 'PRC'
  end;

  if new.protocolo is null or btrim(new.protocolo) = '' then
    new.protocolo := public.portal_gerar_protocolo(prefixo);
  end if;

  if new.prioridade is null or btrim(new.prioridade) = '' then
    new.prioridade := 'NORMAL';
  end if;

  new.updated_at := now();
  return new;
end;
$$;

create or replace function public.portal_auditar_fluxo()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  novo jsonb := to_jsonb(new);
  antigo jsonb := case when tg_op = 'UPDATE' then to_jsonb(old) else '{}'::jsonb end;
  acao_evento text;
  matricula_ator text;
  nome_ator text;
  matricula_destino text;
  status_anterior text;
  status_novo text;
begin
  matricula_ator := coalesce(
    novo ->> 'atualizado_por_matricula',
    novo ->> 'criado_por_matricula',
    novo ->> 'matricula'
  );
  nome_ator := coalesce(
    novo ->> 'atualizado_por_nome',
    novo ->> 'nome_servidor',
    novo ->> 'responsavel'
  );
  matricula_destino := coalesce(novo ->> 'matricula', novo ->> 'criado_por_matricula');
  status_anterior := antigo ->> 'status';
  status_novo := novo ->> 'status';

  if tg_op = 'INSERT' then
    acao_evento := 'CRIACAO';
  elsif status_anterior is distinct from status_novo then
    acao_evento := 'ALTERACAO_STATUS';
  else
    acao_evento := 'ATUALIZACAO';
  end if;

  insert into public.auditoria_eventos (
    tabela, registro_id, protocolo, acao, status_anterior, status_novo,
    usuario_matricula, usuario_nome, detalhes
  ) values (
    tg_table_name,
    coalesce(novo ->> 'id', 'sem-id'),
    novo ->> 'protocolo',
    acao_evento,
    status_anterior,
    status_novo,
    matricula_ator,
    nome_ator,
    jsonb_build_object('prioridade', novo ->> 'prioridade')
  );

  if tg_op = 'UPDATE'
     and status_anterior is distinct from status_novo
     and matricula_destino is not null then
    insert into public.notificacoes (matricula, titulo, mensagem, modulo, protocolo)
    values (
      matricula_destino,
      'Atualização de solicitação',
      'O status foi alterado de ' || coalesce(status_anterior, 'não informado')
        || ' para ' || coalesce(status_novo, 'não informado') || '.',
      tg_table_name,
      novo ->> 'protocolo'
    );
  end if;

  return new;
end;
$$;

do $$
declare
  tabela_nome text;
begin
  foreach tabela_nome in array array[
    'oficios',
    'solicitacoes_almoxarifado',
    'solicitacoes_frota',
    'chamados_patrimonio',
    'solicitacoes_ferias'
  ] loop
    execute format('drop trigger if exists portal_preparar_fluxo_trg on public.%I', tabela_nome);
    execute format(
      'create trigger portal_preparar_fluxo_trg before insert or update on public.%I for each row execute function public.portal_preparar_fluxo()',
      tabela_nome
    );
    execute format('drop trigger if exists portal_auditar_fluxo_trg on public.%I', tabela_nome);
    execute format(
      'create trigger portal_auditar_fluxo_trg after insert or update on public.%I for each row execute function public.portal_auditar_fluxo()',
      tabela_nome
    );
  end loop;
end $$;

