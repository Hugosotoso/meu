-- Migração idempotente: pode ser executada novamente sem apagar dados.

create sequence if not exists public.portal_protocolo_seq start 1;

create or replace function public.portal_gerar_protocolo(prefixo text)
returns text
language sql
volatile
security definer
set search_path = public
as $$
  select upper(prefixo)
    || '-' || to_char(current_date, 'YYYY')
    || '-' || lpad(nextval('public.portal_protocolo_seq')::text, 6, '0');
$$;

