create or replace function public.portal_eh_gestor()
returns boolean
language sql
stable
security definer
set search_path = public, extensions, pg_temp
as $$
  select coalesce(
    (select upper(s.nivel_acesso) = 'DIAMANTE'
     from public.portal_sessao_atual() s
     limit 1),
    false
  );
$$;

create or replace function public.portal_iniciar_sessao(p_cpf text)
returns table (
  session_token text,
  cpf text,
  nome text,
  cargo text,
  uorg_id text,
  matricula text,
  nivel_acesso text,
  expira_em timestamptz
)
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  cpf_limpo text := regexp_replace(coalesce(p_cpf, ''), '[^0-9]', '', 'g');
  servidor public.servidores%rowtype;
  token_aberto text;
  validade timestamptz := now() + interval '8 hours';
begin
  if length(cpf_limpo) <> 11 then
    return;
  end if;

  select s.* into servidor
  from public.servidores s
  where regexp_replace(s.cpf::text, '[^0-9]', '', 'g') = cpf_limpo
  limit 1;

  if not found then
    return;
  end if;

  delete from public.portal_sessoes s
  where s.expira_em <= now()
     or (s.matricula = servidor.matricula::text and s.criado_em < now() - interval '1 hour');

  token_aberto := encode(extensions.gen_random_bytes(32), 'hex');

  insert into public.portal_sessoes (
    token_hash, matricula, cpf, nome, cargo, uorg_id, nivel_acesso, expira_em
  ) values (
    encode(extensions.digest(token_aberto, 'sha256'), 'hex'),
    servidor.matricula::text,
    servidor.cpf::text,
    servidor.nome::text,
    servidor.cargo::text,
    servidor.uorg_id::text,
    coalesce(servidor.nivel_acesso::text, 'OURO'),
    validade
  );

  return query select
    token_aberto,
    servidor.cpf::text,
    servidor.nome::text,
    servidor.cargo::text,
    servidor.uorg_id::text,
    servidor.matricula::text,
    coalesce(servidor.nivel_acesso::text, 'OURO'),
    validade;
end;
$$;

